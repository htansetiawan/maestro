"""Create a deterministic melody guide for proofreading; this is not YuE2."""
from fractions import Fraction
import html
import json
from pathlib import Path
import subprocess

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT/'inputs/source-events.json').read_text())
check = json.loads((ROOT/'prepared/score-check.json').read_text())
sr, bpm = 24000, source['bpm']
audio = np.zeros(round((check['nominal_duration_seconds']+.5)*sr), dtype=np.float32)
for onset, duration, pitch in source['notes']:
    start = round(float(Fraction(onset))*60/bpm*sr)
    length = max(2, round(float(Fraction(duration))*60/bpm*sr))
    t = np.arange(length)/sr
    hz = 440*2**((pitch-69)/12)
    envelope = np.minimum(t/.005, 1)*np.minimum((length/sr-t)/.012, 1)*np.exp(-1.4*t)
    tone = .25*envelope*(np.sin(2*np.pi*hz*t)+.18*np.sin(4*np.pi*hz*t)+.08*np.sin(6*np.pi*hz*t))
    audio[start:start+length] += tone.astype(np.float32)
assert np.isfinite(audio).all() and np.max(np.abs(audio)) < 1
guide = ROOT/'inputs/melody-guide.flac'
sf.write(guide, audio, sr, subtype='PCM_24')
subprocess.run(['ffmpeg','-y','-nostdin','-v','error','-i',str(guide),'-c:a','libmp3lame',
                '-b:a','128k',str(guide.with_suffix('.mp3'))],check=True)
rows = []
for line in (ROOT/'inputs/transcription.tsv').read_text().splitlines():
    if line.startswith('#'):
        continue
    measure, location, section, meter, melody, chords = line.split('|')
    bar = source['bars'][int(measure)]
    seconds = float(Fraction(bar['onset']))*60/bpm
    cells = [f'<button data-seconds="{seconds:.6f}" aria-label="Play from measure {measure}">{measure}</button>',
             html.escape(location), html.escape(section), bar['meter'], html.escape(melody), html.escape(chords)]
    rows.append('<tr>'+''.join('<td>'+c+'</td>' for c in cells)+'</tr>')
